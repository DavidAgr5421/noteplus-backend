from typing import Protocol

from app.domain.entities.ficha import Ficha
from app.domain.entities.instructor import Instructor


class InstructorRepository(Protocol):
    async def find_by_id(self, instructor_id: str) -> Instructor | None: ...
    async def find_by_email(self, email: str) -> Instructor | None: ...
    async def save(self, instructor: Instructor) -> Instructor: ...


class FichaRepository(Protocol):
    async def find_by_id(self, ficha_id: str) -> Ficha | None: ...
    async def find_by_id_and_instructor(  # noqa: E501
        self, ficha_id: str, instructor_id: str
    ) -> Ficha | None: ...
    async def find_by_instructor(self, instructor_id: str, archivada: bool) -> list[Ficha]: ...
    async def find_by_unique(  # noqa: E501
        self, instructor_id: str, codigo: str, fecha_inicio: str
    ) -> Ficha | None: ...
    async def save(self, ficha: Ficha) -> Ficha: ...
    async def delete(self, ficha_id: str) -> None: ...
